package com.photopilot.service;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.photopilot.model.CameraModel;
import com.photopilot.model.CameraModel.Brand;
import com.photopilot.model.CameraModel.Level;
import com.photopilot.model.CameraModel.Series;
import com.photopilot.model.CameraModel.Support;
import com.photopilot.model.CounterKind;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.text.Normalizer;
import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Sony and Nikon camera models from the ExifTool-tested camera list (resource {@code catalog/exiftool-camera-models.json},
 * generated by {@code tools/GenerateCameraCatalog.java} from https://exiftool.org/models.html), grouped by family and
 * series, searchable by brand, family, series, product name, model ID and common naming variants.
 *
 * <p>Being listed only means ExifTool has been tested with the model. Whether a shutter counter is documented for it is
 * decided separately from the MakerNotes definitions of the bundled ExifTool 13.62 (Sony.pm Tag9050a-d, MoreInfo0201 and
 * FocusInfo conditions; Nikon.pm ShotInfo tables and their ShutterCount decryption key), and "verified" only for models
 * checked with a real photograph ({@code catalog/shutter-count-verified.json}). Non-camera entries (phones, camcorders,
 * PDAs, printers, scanners, software) are excluded.
 */
public final class CameraModelCatalog {
    /** Where the catalog came from, for display and for keeping it current. */
    public record Source(String url, String title, String retrieved, String exiftoolVersion, int sourceModelCount,
                         Map<Brand, Integer> listed, Map<Brand, Integer> excluded) {
        public Source { listed = Map.copyOf(listed); excluded = Map.copyOf(excluded); }
    }

    private static final String CATALOG = "/catalog/exiftool-camera-models.json";
    private static final String VERIFIED = "/catalog/shutter-count-verified.json";
    private static volatile CameraModelCatalog bundled;

    private final Source source;
    private final Map<Brand, List<CameraModel>> models = new EnumMap<>(Brand.class);
    private final Map<Brand, Map<String, CameraModel>> exact = new EnumMap<>(Brand.class);
    private final Map<CameraModel, List<String>> haystacks = new HashMap<>();

    /** The catalog shipped with PhotoPilot; loaded once on first use. */
    public static CameraModelCatalog bundled() {
        CameraModelCatalog value = bundled;
        if (value == null) synchronized (CameraModelCatalog.class) {
            value = bundled;
            if (value == null) bundled = value = load(resource(CATALOG), resource(VERIFIED));
        }
        return value;
    }
    private static Reader resource(String name) {
        var stream = CameraModelCatalog.class.getResourceAsStream(name);
        if (stream == null) throw new IllegalStateException("Missing camera catalog resource " + name);
        return new InputStreamReader(stream, StandardCharsets.UTF_8);
    }

    static CameraModelCatalog load(Reader catalog, Reader verified) {
        try (catalog; verified) {
            JsonObject root = JsonParser.parseReader(catalog).getAsJsonObject();
            Set<String> verifiedModels = new HashSet<>();
            for (var entry : JsonParser.parseReader(verified).getAsJsonObject().getAsJsonArray("verified"))
                verifiedModels.add(entry.getAsJsonObject().get("brand").getAsString() + "|" + entry.getAsJsonObject().get("model").getAsString());
            return new CameraModelCatalog(root, verifiedModels);
        } catch (IOException error) { throw new UncheckedIOException(error); }
    }

    private CameraModelCatalog(JsonObject root, Set<String> verifiedModels) {
        Map<Brand, Integer> listed = new EnumMap<>(Brand.class), excluded = new EnumMap<>(Brand.class);
        JsonObject brands = root.getAsJsonObject("brands");
        for (Brand brand : Brand.values()) {
            List<CameraModel> list = new ArrayList<>();
            var names = brands.getAsJsonArray(brand.label());
            if (names == null) throw new IllegalStateException("Camera catalog has no " + brand.label() + " section");
            int dropped = 0;
            for (var element : names) {
                String id = element.getAsString().strip();
                Optional<Series> series = classify(brand, id);
                if (series.isEmpty()) { dropped++; continue; }
                Support support = support(brand, id);
                if (verifiedModels.contains(brand.label() + "|" + id)) support = support.verified();
                list.add(new CameraModel(brand, id, displayName(brand, id), series.get(), aliases(brand, id), support));
            }
            listed.put(brand, names.size()); excluded.put(brand, dropped);
            // Series order, then ExifTool's own (numeric-aware) listing order within a series.
            list.sort(Comparator.comparing(CameraModel::series));
            models.put(brand, List.copyOf(list));
            Map<String, CameraModel> keys = new HashMap<>();
            for (CameraModel model : list) {
                for (String key : model.aliases()) {
                    CameraModel previous = keys.putIfAbsent(key, model);
                    if (previous != null && previous != model)
                        throw new IllegalStateException("Ambiguous camera name " + key + ": " + previous.id() + " / " + model.id());
                }
                List<String> hay = new ArrayList<>(model.aliases());
                hay.add(normalize(model.series().name().substring(model.series().name().indexOf('_') + 1)));
                hay.add(normalize(model.series().family().name().substring(model.series().family().name().indexOf('_') + 1)));
                haystacks.put(model, List.copyOf(hay));
            }
            exact.put(brand, Map.copyOf(keys));
        }
        source = new Source(root.get("source").getAsString(), root.get("sourceTitle").getAsString(), root.get("retrieved").getAsString(),
            root.get("exiftoolVersion").getAsString(), root.get("sourceModelCount").getAsInt(), listed, excluded);
    }

    public Source source() { return source; }
    public List<CameraModel> models(Brand brand) { return models.get(brand); }
    /** Series that have at least one model, in display order. */
    public List<Series> series(Brand brand) { return models.get(brand).stream().map(CameraModel::series).distinct().toList(); }

    /**
     * Models of a brand, optionally within one series, whose name, ID, family, series or naming variant contains the
     * query (case, spaces, hyphens, "α"/"Alpha" and a leading brand name are ignored). A blank query matches all.
     */
    public List<CameraModel> search(Brand brand, Optional<Series> series, String query) {
        String wanted = withoutBrand(normalize(query == null ? "" : query));
        return models.get(brand).stream().filter(model -> series.isEmpty() || model.series() == series.get())
            .filter(model -> wanted.isEmpty() || haystacks.get(model).stream().anyMatch(text -> text.contains(wanted))).toList();
    }

    /** Exact lookup by model ID, product name or naming variant (for example "ILCE-7M4", "A7 IV", "Alpha 7 IV"). */
    public Optional<CameraModel> resolve(Brand brand, String name) {
        return Optional.ofNullable(exact.get(brand).get(withoutBrand(normalize(name))));
    }

    /** The catalog entry for a photo's EXIF Make and Model ("SONY"/"ILCE-7RM5", "NIKON CORPORATION"/"NIKON Z 6_2"). */
    public Optional<CameraModel> detect(String make, String model) {
        return Brand.fromMake(make).flatMap(brand -> model == null ? Optional.empty() : resolve(brand, model));
    }

    /** Lowercase letters and digits only; "α" and "alpha" become "a", so "α7 IV", "Alpha 7 IV" and "A7IV" compare equal. */
    public static String normalize(String text) {
        String value = Normalizer.normalize(text, Normalizer.Form.NFKC).toLowerCase(Locale.ROOT).replace('α', 'a').replace("alpha", "a");
        return value.replaceAll("[^a-z0-9]", "");
    }
    private static String withoutBrand(String normalized) {
        for (String prefix : List.of("nikoncorporation", "nikon", "sony"))
            if (normalized.startsWith(prefix) && normalized.length() > prefix.length()) return normalized.substring(prefix.length());
        return normalized;
    }

    // ---- Classification: photographic cameras only, grouped by series --------------------------------------------

    private static final Pattern SONY_EXCLUDED = Pattern.compile(
        "^([CDEFGHJ]\\d{4}|XQ-.*|Xperia.*|CLIE.*|DCR-.*|DSR-.*|DPP-.*|DVgate.*|FDR-.*|GV-.*|HANDYCAM|HDR-.*|HVR-.*|HXR-.*|MHS-.*|MODEL-NAME|PMW-.*|PSP-.*|UPX|NEX-VG.*)$");

    /** The series of a listed name, or empty for entries that are not photographic camera models (or not recognised). */
    static Optional<Series> classify(Brand brand, String id) {
        return Optional.ofNullable(brand == Brand.SONY ? sonySeries(id) : nikonSeries(id));
    }
    private static Series sonySeries(String id) {
        if (SONY_EXCLUDED.matcher(id).matches()) return null;
        if (id.matches("ILCE-1(M\\d)?")) return Series.SONY_ALPHA_1;
        if (id.matches("ILCE-9(M\\d)?")) return Series.SONY_ALPHA_9;
        if (id.matches("ILCE-7(M\\d)?")) return Series.SONY_ALPHA_7;
        if (id.matches("ILCE-7R(M\\d)?A?")) return Series.SONY_ALPHA_7R;
        if (id.matches("ILCE-7S(M\\d)?")) return Series.SONY_ALPHA_7S;
        if (id.matches("ILCE-7C(M\\d|R)?")) return Series.SONY_ALPHA_7C;
        if (id.matches("ILCE-6\\d{3}A?")) return Series.SONY_ALPHA_6000;
        if (id.matches("ILCE-[35]\\d{3}")) return Series.SONY_ALPHA_5000_3000;
        if (id.matches("(ILCE|DSC)-QX\\d+")) return Series.SONY_QX;
        if (id.startsWith("NEX-")) return Series.SONY_NEX;
        if (id.startsWith("SLT-") || id.startsWith("ILCA-")) return Series.SONY_A_MOUNT_SLT_ILCA;
        if (id.startsWith("DSLR-A")) return Series.SONY_A_MOUNT_DSLR;
        if (id.startsWith("ILME-")) return Series.SONY_CINEMA_LINE;
        if (id.startsWith("ZV-")) return Series.SONY_ZV;
        if (id.startsWith("DSC-RX")) return Series.SONY_RX;
        if (id.startsWith("DSC-")) return Series.SONY_CYBER_SHOT;
        if (id.startsWith("MVC-")) return Series.SONY_MAVICA;
        if (id.startsWith("NSC-")) return Series.SONY_OTHER;
        return null;
    }
    private static Series nikonSeries(String id) {
        if (id.startsWith("CaptureNX") || id.startsWith("NXStudio") || id.startsWith("Coolscan")) return null;
        if (id.matches("Z ?(30|50|50_2|fc)")) return Series.NIKON_Z_DX;
        if (id.matches("Z ?(5|6|6_2|6_3|7|7_2|8|9|f|R)")) return Series.NIKON_Z_FULL_FRAME;
        if (id.matches("D\\d[A-Za-z]*")) return Series.NIKON_D_SINGLE_DIGIT;
        if (id.matches("D\\d{2}[A-Za-z]*")) return Series.NIKON_D_TWO_DIGIT;
        if (id.matches("D\\d{3}[A-Za-z]*")) return Series.NIKON_D_THREE_DIGIT;
        if (id.matches("D\\d{4}")) return Series.NIKON_D_FOUR_DIGIT;
        if (id.equals("Df")) return Series.NIKON_DF;
        if (id.matches("1 [A-Z]+\\d+")) return Series.NIKON_1;
        if (id.startsWith("Coolpix ")) return Series.NIKON_COOLPIX;
        if (id.startsWith("KeyMission ")) return Series.NIKON_KEYMISSION;
        if (id.equals("SQ")) return Series.NIKON_OTHER;
        return null;
    }

    // ---- Product names and naming variants -------------------------------------------------------------------------

    private static final String[] ROMAN = { "", "", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX" };
    private static final Pattern MARK = Pattern.compile("^(.*?)M([2-9])(A?)$");

    /** Sony's "M2..M9" mark suffix as a Roman numeral ("7RM5" -> "7R V", "RX100M5A" -> "RX100 VA"). */
    private static String roman(String base) {
        Matcher m = MARK.matcher(base);
        return m.matches() ? m.group(1) + " " + ROMAN[m.group(2).charAt(0) - '0'] + m.group(3) : base;
    }
    static String displayName(Brand brand, String id) {
        if (brand == Brand.SONY) {
            if (id.startsWith("ILCE-QX")) return "α " + id.substring(5);
            if (id.startsWith("ILCE-") || id.startsWith("ILCA-")) return "α" + roman(id.substring(5));
            if (id.startsWith("SLT-A")) return "α" + id.substring(5);
            if (id.startsWith("DSLR-A")) return "α" + id.substring(6);
            if (id.startsWith("ILME-")) return roman(id.substring(5));
            if (id.startsWith("DSC-RX")) return roman(id.substring(4));
            if (id.startsWith("DSC-QX")) return id.substring(4);
            if (id.startsWith("DSC-")) return "Cyber-shot " + id.substring(4);
            if (id.startsWith("ZV-")) return roman(id);
            return id;
        }
        Matcher mark = Pattern.compile("^(Z ?\\d+)_([2-9])$").matcher(id);
        if (mark.matches()) return mark.group(1) + ROMAN[mark.group(2).charAt(0) - '0'];
        if (id.startsWith("Coolpix ")) return "COOLPIX " + id.substring(8);
        if (id.matches("1 [A-Z]+\\d+")) return "Nikon " + id;
        return id;
    }
    /** Normalized names that identify the model exactly: its ID, product name and common variants. */
    static List<String> aliases(Brand brand, String id) {
        Set<String> names = new LinkedHashSet<>();
        names.add(normalize(id));
        names.add(normalize(displayName(brand, id)));
        if (brand == Brand.SONY) {
            if (id.startsWith("ILCE-") || id.startsWith("ILCA-")) {
                String base = id.substring(5);
                names.add(normalize("a" + base));                            // A7RM5, A99M2
                names.add(normalize("a" + base.replaceAll("M(\\d)(A?)$", "$1$2"))); // A7R5, A74
            }
            if (id.startsWith("DSC-")) names.add(normalize(id.substring(4)));  // RX100M7, W800
        } else {
            if (id.startsWith("Coolpix ")) names.add(normalize(id.substring(8)));
        }
        return List.copyOf(names);
    }

    // ---- Shutter counter support (ported from the bundled ExifTool 13.62 Sony.pm / Nikon.pm conditions) ----------

    // Sony.pm 0x9050 sub-table conditions, verbatim.
    private static final Pattern SONY_9050A_EXCLUDED = Pattern.compile("^(DSC-|Stellar|ILCE-(1|6100|6300|6400|6500|6600|6700|7C|7M3|7M4|7M5|7RM2|7RM3A?|7RM4A?|7RM5|7RM6|7SM2|7SM3|9|9M2)|ILCA-99M2|ILME-(FX2|FX3)|ZV-)");
    private static final Pattern SONY_9050B = Pattern.compile("^(ILCE-(6100A?|6300|6400A?|6500|6600|7C|7M3|7RM2|7RM3A?|7RM4A?|7SM2|9|9M2)|ILCA-99M2|ZV-E10)\\b");
    private static final Pattern SONY_9050C = Pattern.compile("^(ILCE-(1\\b|7M4|7RM5|7SM3)|ILME-FX3)");
    private static final Pattern SONY_9050D = Pattern.compile("^(ILCE-(6700|7CM2|7CR)|ILME-FX2|ZV-(E1|E10M2))\\b");
    private static final Pattern SONY_9050D_MECHANICAL_ONLY = Pattern.compile("^(ILCE-(1M2|7M5|7RM6))");
    private static final Pattern SONY_9050D_COUNT = Pattern.compile("^(ILCE-(1M2|6700|7CM2|7CR|7M5|7RM6)|ILME-FX2)");
    // Models the Tag9050a source comments name for ShutterCount / ShutterCount2 / ShutterCount3.
    private static final Pattern SONY_9050A_NAMED = Pattern.compile("^(SLT-A(37|57|58|65V?|77V?|99V?)|NEX-(3N|5N|5R|5T|6|7|F3)|ILCE-|ILCA-)");
    // MoreInfo (A450/A500/A550/A560/A580/A33/A35/A55/NEX-3/5/C3) MoreInfo0201 ShutterCount; FocusInfo ShutterCount condition.
    private static final Pattern SONY_MOREINFO = Pattern.compile("^(DSLR-A(450|500|550|560|580)|SLT-A(33|35|55V?)|NEX-(3|5|C3))$");
    private static final Pattern SONY_FOCUSINFO = Pattern.compile("^DSLR-A(230|290|330|380|390|850|900)$");
    // Nikon.pm: ShotInfo tables with a ShutterCount field, the ImageCount + DeletedImageCount = ShutterCount comment, and
    // models whose encrypted ShotInfo ExifTool decodes with the ShutterCount (0x00a7) key, as named in the 0x0091 entries.
    private static final Set<String> NIKON_SHOTINFO_COUNT = Set.of("D40", "D50", "D60", "D80", "D90", "D2X", "D2Xs", "D3", "D3X", "D3S",
        "D300", "D300S", "D700", "D800", "D5000", "D5100", "D5200", "D7000");
    private static final Set<String> NIKON_COUNT_SUM = Set.of("D2H", "D2Hs", "D200");
    private static final Set<String> NIKON_ENCRYPTED = Set.of("D3000", "D3100", "D3200", "D7100", "D610", "D4", "D4S", "D5", "D500",
        "D6", "D780", "D7500", "D810", "D850", "Z 5", "Z 6", "Z 7", "Z 50", "Z 6_2", "Z 7_2", "Z fc", "Z 30", "Z f", "Z6_3", "Z50_2", "Z 8", "Z 9");
    private static final String NIKON_FIELD = "Nikon MakerNotes ShutterCount (0x00a7)";

    static Support support(Brand brand, String id) {
        return brand == Brand.SONY ? sonySupport(id) : nikonSupport(id);
    }
    private static Support documented(String field, CounterKind kind, String condition, String evidence) {
        return new Support(Level.DOCUMENTED, Optional.of(field), Optional.of(kind), Optional.ofNullable(condition), evidence);
    }
    private static Support absent(Level level, String evidence) {
        return new Support(level, Optional.empty(), Optional.empty(), Optional.empty(), evidence);
    }
    private static Support sonySupport(String id) {
        boolean table9050d = SONY_9050D.matcher(id).find() || SONY_9050D_MECHANICAL_ONLY.matcher(id).find();
        if (table9050d && SONY_9050D_COUNT.matcher(id).find())
            return documented("Sony Tag9050d ShutterCount", CounterKind.MECHANICAL_ACTUATIONS,
                SONY_9050D_MECHANICAL_ONLY.matcher(id).find() ? "shutter.condition.mechanicalOnly" : null, "shutter.evidence.sony9050d");
        if (table9050d) return absent(Level.UNAVAILABLE, "shutter.evidence.sony9050dNoCount");
        if (SONY_9050C.matcher(id).find()) return documented("Sony Tag9050c ShutterCount", CounterKind.TOTAL_EXPOSURES, "shutter.condition.silent", "shutter.evidence.sony9050c");
        if (SONY_9050B.matcher(id).find()) return documented("Sony Tag9050b ShutterCount", CounterKind.TOTAL_EXPOSURES, "shutter.condition.silent", "shutter.evidence.sony9050b");
        if (!SONY_9050A_EXCLUDED.matcher(id).find() && SONY_9050A_NAMED.matcher(id).find())
            return documented("Sony Tag9050a ShutterCount", CounterKind.TOTAL_EXPOSURES, "shutter.condition.modulo", "shutter.evidence.sony9050a");
        if (SONY_MOREINFO.matcher(id).matches()) return documented("Sony MoreInfo0201 ShutterCount", CounterKind.SHUTTER_COUNT, null, "shutter.evidence.sonyMoreInfo");
        if (SONY_FOCUSINFO.matcher(id).matches()) return documented("Sony FocusInfo ShutterCount", CounterKind.SHUTTER_COUNT, "shutter.condition.equalsImageCount", "shutter.evidence.sonyFocusInfo");
        if (id.startsWith("DSC-") || id.startsWith("ZV-") || id.startsWith("MVC-") || id.startsWith("NSC-"))
            return absent(Level.UNAVAILABLE, "shutter.evidence.sonyCompact");
        if (id.startsWith("DSLR-A")) return absent(Level.UNAVAILABLE, "shutter.evidence.sonyDslrNone");
        if (SONY_9050A_EXCLUDED.matcher(id).find()) return absent(Level.UNAVAILABLE, "shutter.evidence.sonyNoTable");
        return absent(Level.UNVERIFIED, "shutter.evidence.sonyPossible");
    }
    private static Support nikonSupport(String id) {
        if (NIKON_SHOTINFO_COUNT.contains(id)) return documented(NIKON_FIELD, CounterKind.SHOTS_INCLUDING_ELECTRONIC, null, "shutter.evidence.nikonShotInfo");
        if (NIKON_COUNT_SUM.contains(id)) return documented(NIKON_FIELD, CounterKind.SHOTS_INCLUDING_ELECTRONIC, null, "shutter.evidence.nikonSum");
        if (NIKON_ENCRYPTED.contains(id)) return documented(NIKON_FIELD, CounterKind.SHOTS_INCLUDING_ELECTRONIC, null, "shutter.evidence.nikonEncrypted");
        return absent(Level.UNVERIFIED, "shutter.evidence.nikonUnverified");
    }
}
